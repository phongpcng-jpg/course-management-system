package io.github.nguyenquephong13062003.course_management_system.models.constants;

/**
 * Enumeration representing the possible enrollment statuses for a course.
 * This enum defines the different states that a user's enrollment in a course can have.
 */
public enum EnrollmentStatus {
    
    /**
     * Indicates that the user is currently enrolled in the course.
     */
    ENROLLED,

    /**
     * Indicates that the user has completed the course.
     */
    COMPLETED,

    /**
     * Indicates that the user has dropped the course.
     */
    DROPPED
    
}
