package io.github.nguyenquephong13062003.course_management_system.models.constants;

/**
 * Enum representing the status of a course.
 */
public enum CourseStatus {

    /**
     * The course is in draft status and not yet published.
     */
    DRAFT,

    /**
     * The course is published and available for enrollment.
     */
    PUBLISHED,

    /**
     * The course is archived and no longer available for enrollment.
     */
    ARCHIVED
}
